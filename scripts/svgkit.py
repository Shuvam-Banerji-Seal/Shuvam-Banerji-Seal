FONT_START, FONT_END = "/*FONTS-START*/", "/*FONTS-END*/"


def doc(w, h, body, defs="", css="", title="", desc="", fonts_css="") -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" '
        f'viewBox="0 0 {w} {h}" width="{w}" height="{h}" role="img" aria-labelledby="t d">\n'
        f"<title id=\"t\">{esc(title)}</title><desc id=\"d\">{esc(desc)}</desc>\n"
        "<!-- Generated by scripts/build_svgs.py. Embedded font subsets: JetBrains Mono and "
        "Noto Serif JP, both under the SIL Open Font License 1.1. -->\n"
        f"<defs><style>{FONT_START}{fonts_css}{FONT_END}\n"
        f".m{{font-family:{MONO}}}.j{{font-family:{SERIF_JP}}}{css}</style>\n"
        f"{common_defs()}{defs}</defs>\n{body}\n</svg>\n"
    )


