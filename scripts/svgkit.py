def _glyph(ch: str, color: str, core: str, sw: float, csw: float) -> str:
    if ch == ".":
        return f'<circle cx="20" cy="63" r="3.8" fill="{color}"/><circle cx="20" cy="63" r="1.6" fill="{core}"/>'
    d = DIGITS[ch]
    return (
        f'<path d="{d}" fill="none" stroke="{color}" stroke-width="{sw}" stroke-linecap="round" stroke-linejoin="round" vector-effect="non-scaling-stroke"/>'
        f'<path d="{d}" fill="none" stroke="{core}" stroke-width="{csw}" stroke-linecap="round" stroke-linejoin="round" vector-effect="non-scaling-stroke"/>'
    )


def scramble_timeline(segments, n, dur, seed=7, step=0.065):
    """segments: [(t, "1.048596"), (t, None), ...]; None = scramble until the next hold.

    Returns per-tube event lists [(t, ch)] where ch is a digit, '.' or ' ' (off).
    Tubes lock left-to-right at the end of each scramble window.
    """
    rnd = random.Random(seed)
    tubes = [[] for _ in range(n)]
    for k, (t0, val) in enumerate(segments):
        t1 = segments[k + 1][0] if k + 1 < len(segments) else dur
        if val is not None:
            for i in range(n):
                tubes[i].append((t0, val[i]))
            continue
        nxt = next(v for (_, v) in segments[k + 1:] if v is not None)
        span = max(t1 - t0 - 0.3, 0.2)
        for i in range(n):
            lock = t0 + 0.25 + i * span / max(n - 1, 1)
            t, prev = t0, None
            while t < lock - 1e-9:
                if nxt[i] == ".":
                    ch = " " if prev == "." else "."
                else:
                    ch = rnd.choice([d for d in "0123456789" if d != prev])
                tubes[i].append((t, ch))
                prev, t = ch, t + step
            tubes[i].append((lock, nxt[i]))
    return tubes


def _onoff(events, glyph):
    out = []
    for t, ch in events:
        v = 1 if ch == glyph else 0
        if not out or out[-1][1] != v:
            out.append((t, v))
    if out and out[0][0] > 0:
        out.insert(0, (0.0, 1 - out[0][1]))
    return out


def _anim(onoff, dur, once):
    kt = ";".join(f"{min(t / dur, 1):.4f}" for t, _ in onoff)
    vals = ";".join(str(v) for _, v in onoff)
    rep = 'fill="freeze"' if once else 'repeatCount="indefinite"'
    return f'<animate attributeName="opacity" calcMode="discrete" dur="{dur}s" keyTimes="{kt}" values="{vals}" {rep}/>'


def nixie_row(x0, y0, base, tube_w, tube_h, gap, timeline=None, dur=None, once=False,
              uid="nx", plinth=True, flicker=True) -> str:
    """Row of nixie tubes showing `base` statically, optionally animated via `timeline`."""
    out = []
    n = len(base)
    total_w = n * tube_w + (n - 1) * gap
    r = tube_w / 2
    s = (tube_h * 0.56) / 70.0
    gw = 40 * s
    sw = max(1.8, tube_w * 0.05)
    csw = max(0.7, sw * 0.36)
    if plinth:
        py = y0 + tube_h - 4
        out.append(f'<ellipse cx="{x0 + total_w / 2:.1f}" cy="{py + 14:.1f}" rx="{total_w * 0.55:.1f}" ry="{tube_h * 0.16:.1f}" fill="url(#emberglow)" opacity=".7"/>')
        out.append(f'<rect x="{x0 - 22:.1f}" y="{py:.1f}" width="{total_w + 44:.1f}" height="{tube_h * 0.15:.1f}" rx="5" fill="url(#metal)" stroke="#342e40" stroke-width="1"/>')
        for sx in (x0 - 11, x0 + total_w + 11):
            out.append(f'<circle cx="{sx:.1f}" cy="{py + tube_h * 0.075:.1f}" r="3" fill="#0d0b12" stroke="#4a4258" stroke-width="1"/>')
    for i in range(n):
        x = x0 + i * (tube_w + gap)
        cx = x + r
        body = (f"M{x:.1f},{y0 + r:.1f} A{r:.1f},{r:.1f} 0 0 1 {x + tube_w:.1f},{y0 + r:.1f} "
                f"L{x + tube_w:.1f},{y0 + tube_h - 6:.1f} Q{x + tube_w:.1f},{y0 + tube_h:.1f} {x + tube_w - 6:.1f},{y0 + tube_h:.1f} "
                f"L{x + 6:.1f},{y0 + tube_h:.1f} Q{x:.1f},{y0 + tube_h:.1f} {x:.1f},{y0 + tube_h - 6:.1f} Z")
        cid = f"{uid}c{i}"
        out.append(f'<clipPath id="{cid}"><path d="{body}"/></clipPath>')
        out.append(f'<path d="{body}" fill="#0a0810" opacity=".55"/>')
        gx, gy = cx - gw / 2, y0 + tube_h * 0.27
        tr = f'translate({gx:.2f} {gy:.2f}) scale({s:.4f})'
        # ghost digits (unlit cathode stack)
        ghosts = "".join(
            f'<path d="{DIGITS[d]}" fill="none" stroke="#4d3628" stroke-width="1.1" vector-effect="non-scaling-stroke"/>'
            for d in "1742935860")
        out.append(f'<g transform="{tr}" opacity=".5">{ghosts}</g>')
        out.append(f'<rect x="{x:.1f}" y="{y0:.1f}" width="{tube_w}" height="{tube_h}" fill="url(#mesh)" clip-path="url(#{cid})" opacity=".22"/>')
        # lit glyphs
        lit = []
        ev = timeline[i] if timeline else None
        for g in GLYPHS:
            on_static = 1 if base[i] == g else 0
            anim = ""
            if ev:
                oo = _onoff(ev, g)
                if any(v for _, v in oo) or on_static:
                    anim = _anim(oo, dur, once)
                elif not on_static:
                    continue
            elif not on_static:
                continue
            lit.append(f'<g opacity="{on_static}">{anim}{_glyph(g, "#FF8A2A", "#FFE0B0", sw, csw)}</g>')
        fl = ""
        if flicker:
            fl = (f'<animate attributeName="opacity" values="1;.86;1;1;.93;1" keyTimes="0;.03;.06;.5;.53;1" '
                  f'dur="{5.3 + i * 0.73:.2f}s" repeatCount="indefinite"/>')
        out.append(f'<g filter="url(#nx)">{fl}<g transform="{tr}">{"".join(lit)}</g></g>')
        # glass + highlights
        out.append(f'<path d="{body}" fill="url(#glass)" stroke="#ffd9b0" stroke-opacity=".2" stroke-width="1"/>')
        out.append(f'<path d="M{x + tube_w * 0.17:.1f},{y0 + r * 0.9:.1f} L{x + tube_w * 0.17:.1f},{y0 + tube_h - 16:.1f}" stroke="#fff" stroke-opacity=".10" stroke-width="{tube_w * 0.05:.1f}" stroke-linecap="round"/>')
        out.append(f'<path d="M{cx - 4:.1f},{y0 + 2:.1f} Q{cx:.1f},{y0 - 7:.1f} {cx + 4:.1f},{y0 + 2:.1f}" fill="#0a0810" stroke="#ffd9b0" stroke-opacity=".25" stroke-width="1"/>')
    return "\n".join(out)


