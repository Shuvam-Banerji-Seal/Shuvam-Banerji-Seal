def frame(w, h, accent, idx, title, jp, meta) -> str:
    """Card background, border, corner brackets and the header strip."""
    s = [
        f'<rect width="{w}" height="{h}" rx="16" fill="{C["bg"]}"/>',
        f'<rect width="{w}" height="{h}" rx="16" fill="url(#dots)"/>',
        f'<rect width="{w}" height="{h}" rx="16" fill="url(#scan)"/>',
        f'<rect width="{w}" height="{h}" rx="16" fill="url(#vig)"/>',
        f'<rect x=".75" y=".75" width="{w - 1.5}" height="{h - 1.5}" rx="15.5" fill="none" stroke="{C["line"]}" stroke-width="1.5"/>',
    ]
    b = 18
    for (x, y, dx, dy) in ((10, 10, 1, 1), (w - 10, 10, -1, 1), (10, h - 10, 1, -1), (w - 10, h - 10, -1, -1)):
        s.append(f'<path d="M{x},{y + dy * b} L{x},{y} L{x + dx * b},{y}" fill="none" stroke="{accent}" stroke-width="1.6" opacity=".75"/>')
    # header
    s.append(
        f'<g transform="translate(36 29) rotate(45)"><rect x="-4.5" y="-4.5" width="9" height="9" fill="{accent}">'
        f'<animate attributeName="opacity" values="1;.35;1" dur="2.4s" repeatCount="indefinite"/></rect></g>'
    )
    x = 52
    s.append(text(x, 34, idx, 12, C["dim"], 700))
    x += tw(idx, 12) + 12
    s.append(text(x, 34, title, 14, accent, 700, ls=4))
    x += tw(title, 14, 4) + 10
    if jp:
        s.append(text(x, 34, jp, 13, C["muted"], 700, jp=True, op=".9"))
    if meta:
        s.append(text(w - 30, 34, meta, 11, C["dim"], 400, anchor="end", ls=2))
    gid = "hdrule"  # one frame per SVG, so a fixed id is safe (and keeps builds deterministic)
    s.append(
        f'<linearGradient id="{gid}" x1="0" y1="0" x2="1" y2="0"><stop offset="0" stop-color="{accent}" stop-opacity=".7"/>'
        f'<stop offset=".6" stop-color="{accent}" stop-opacity=".12"/><stop offset="1" stop-color="{accent}" stop-opacity="0"/></linearGradient>'
        f'<rect x="28" y="49" width="{w - 56}" height="1.2" fill="url(#{gid})"/>'
    )
    return "\n".join(s)


