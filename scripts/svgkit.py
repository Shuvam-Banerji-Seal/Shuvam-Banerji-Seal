SERIF_JP = "'NSJ','Noto Serif JP','Hiragino Mincho ProN','Yu Mincho',serif"


def esc(s) -> str:
    return escape(str(s), quote=False)


def attr(s) -> str:
    return escape(str(s), quote=True)


def is_jp(ch: str) -> bool:
    o = ord(ch)
    return 0x3000 <= o <= 0x30FF or 0x4E00 <= o <= 0x9FFF or 0xFF00 <= o <= 0xFFEF


def tw(s: str, size: float, ls: float = 0.0) -> float:
    """Advance width of a string set in JetBrains Mono (+ JP glyphs at 1em)."""
    return sum((size if is_jp(ch) else 0.6 * size) + ls for ch in s)


def text(x, y, s, size=12, fill=None, weight=400, anchor="start", ls=0.0,
         jp=False, op=None, extra="", raw=False) -> str:
    fill = fill or C["text"]
    cls = "j" if jp else "m"
    parts = [f'<text class="{cls}" x="{x:.1f}" y="{y:.1f}" font-size="{size}"',
             f' font-weight="{weight}" fill="{fill}"']
    if anchor != "start":
        parts.append(f' text-anchor="{anchor}"')
    if ls:
        parts.append(f' letter-spacing="{ls}"')
    if op is not None:
        parts.append(f' opacity="{op}"')
    if extra:
        parts.append(" " + extra)
    parts.append(">" + (s if raw else esc(s)) + "</text>")
    return "".join(parts)


