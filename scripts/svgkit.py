def gear(cx, cy, r, teeth, th, color, sw, op, dur, rev=False) -> str:
    pts = []
    da = 2 * math.pi / teeth
    for k in range(teeth):
        a = k * da
        for frac, rr in ((0.0, r), (0.14, r + th), (0.36, r + th), (0.5, r)):
            ang = a + frac * da
            pts.append(f"{rr * math.cos(ang):.1f},{rr * math.sin(ang):.1f}")
    path = "M" + " L".join(pts) + " Z"
    spokes = "".join(
        f'<line x1="{r * 0.2 * math.cos(k * 2 * math.pi / 5):.1f}" y1="{r * 0.2 * math.sin(k * 2 * math.pi / 5):.1f}" '
        f'x2="{r * 0.62 * math.cos(k * 2 * math.pi / 5):.1f}" y2="{r * 0.62 * math.sin(k * 2 * math.pi / 5):.1f}"/>'
        for k in range(5))
    to = -360 if rev else 360
    return (f'<g transform="translate({cx} {cy})" opacity="{op}"><g fill="none" stroke="{color}" stroke-width="{sw}">'
            f'<animateTransform attributeName="transform" type="rotate" from="0" to="{to}" dur="{dur}s" repeatCount="indefinite"/>'
            f'<path d="{path}"/><circle r="{r * 0.62:.1f}"/><circle r="{r * 0.2:.1f}"/>{spokes}</g></g>')


def catmull_path(pts) -> str:
    d = f"M{pts[0][0]:.1f},{pts[0][1]:.1f}"
    for i in range(len(pts) - 1):
        p0 = pts[i - 1] if i > 0 else pts[i]
        p1, p2 = pts[i], pts[i + 1]
        p3 = pts[i + 2] if i + 2 < len(pts) else p2
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        d += f" C{c1[0]:.1f},{c1[1]:.1f} {c2[0]:.1f},{c2[1]:.1f} {p2[0]:.1f},{p2[1]:.1f}"
    return d


def catmull_y_at(pts, x) -> float:
    """y of the Catmull-Rom curve through pts at horizontal position x (x must be monotone)."""
    best = None
    for i in range(len(pts) - 1):
        p0 = pts[i - 1] if i > 0 else pts[i]
        p1, p2 = pts[i], pts[i + 1]
        p3 = pts[i + 2] if i + 2 < len(pts) else p2
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        for k in range(201):
            t = k / 200
            mt = 1 - t
            bx = mt**3 * p1[0] + 3 * mt * mt * t * c1[0] + 3 * mt * t * t * c2[0] + t**3 * p2[0]
            by = mt**3 * p1[1] + 3 * mt * mt * t * c1[1] + 3 * mt * t * t * c2[1] + t**3 * p2[1]
            if best is None or abs(bx - x) < best[0]:
                best = (abs(bx - x), by)
    return best[1]
